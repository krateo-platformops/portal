#!/usr/bin/env python3
"""Inferred inputs (core-provider #568 child 7), over the charts' OWN jq.

When a blueprint's chart ships no values.schema.json, core-provider infers the spec schema from
values.yaml, marks the published jsonschema ConfigMap's ROOT with x-krateo-values-schema:
{source: inferred, rules: "1"}, and sets ValuesSchemaAuthored=False/InferredFromValues on the
CompositionDefinition. Approved mockup: https://claude.ai/artifact/TqxGgtmyM8smwiE83BMEjD.

The inputs are core-provider's envtest sample, measured on a real apiserver
(~/krateo/samples/568-marker, inlined byte for byte):
  inferred           a chart with typed values: the notice, no "accept any value" sentence
  untyped            the six-leaf fixture: null, 0.5, [1, true], [[1],[2]], a nested null, []
  authored           an authored values.schema.json: nothing anywhere
  forged             authored, with a forged marker that core-provider stripped (byte-identical)
This runs, as they ship: blueprint-formdef's filter and the Create Form's `notices`,
composition-editdef's filter and the Edit Form's `notices`, and blueprint-detail's filter with the
info Descriptions' items. The untyped fields must equal the list core-provider measured on the CRD
side (B_crdAnyValue: the fields a person sees), not its report (`lists[]` where the form says `lists`;
since plumbing v1.105.0 the report also lists `empty[]`, so the two counts agree).
A control: treating an `items: {}` array as typed must lose `lists` and `mixedKinds`.
"""
import json
import os
import subprocess
import sys
import tempfile

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
BLUEPRINTS = os.environ.get('BLUEPRINTS_CHART') or os.path.join(ROOT, 'helm', 'blueprints-page')
COMPOSITIONS = os.environ.get('COMPOSITIONS_CHART') or os.path.join(ROOT, 'helm', 'compositions-page')
JQ = os.environ.get('JQ', 'jq')

# ~/krateo/samples/568-marker, raw ConfigMap values.schema.json, exactly as written to the apiserver.
CM_INFERRED = '{"type":"object","properties":{"global":{"type":"object"},"replicas":{"x-kubernetes-int-or-string":true,"default":2},"image":{"type":"object","properties":{"repository":{"x-kubernetes-int-or-string":true,"default":"nginx"},"tag":{"x-kubernetes-int-or-string":true,"default":"1.27"}},"additionalProperties":true},"labels":{"type":"object"}},"additionalProperties":true,"x-krateo-values-schema":{"source":"inferred","rules":"1"}}'
CM_UNTYPED = '{"type":"object","properties":{"global":{"type":"object"},"replicas":{"x-kubernetes-int-or-string":true,"default":2},"labels":{"type":"object"},"nothing":{},"ratio":{"default":0.5},"mixed":{"type":"array","items":{"x-kubernetes-int-or-string":true},"default":[1,"a"]},"mixedKinds":{"type":"array","items":{},"default":[1,true]},"lists":{"type":"array","items":{},"default":[[1],[2]]},"nested":{"type":"object","properties":{"deep":{}},"additionalProperties":true},"empty":{"type":"array","default":[]}},"additionalProperties":true,"x-krateo-values-schema":{"source":"inferred","rules":"1"}}'
CM_AUTHORED = '{"$schema":"https://json-schema.org/draft-07/schema#","type":"object","properties":{"replicas":{"type":"integer","default":2},"image":{"type":"object","properties":{"repository":{"type":"string","default":"nginx"},"tag":{"type":"string","default":"1.27"}}},"labels":{"type":"object","additionalProperties":true}}}'
CM_FORGED = CM_AUTHORED  # the forged-marker case: core-provider's ConfigMap is byte-identical to authored
# core-provider's measured lists for the six-leaf fixture (inferred.untyped-paths.json).
CRD_ANY_VALUE = ['empty', 'lists', 'mixedKinds', 'nested.deep', 'nothing', 'ratio']
REPORT_UNTYPED = ['empty[]', 'lists[]', 'mixedKinds[]', 'nested.deep', 'nothing', 'ratio']  # plumbing v1.105.0 (core-provider #620): gains empty[]

COND_INFERRED = {'type': 'ValuesSchemaAuthored', 'status': 'False', 'reason': 'InferredFromValues',
                 'message': 'the chart ships no values.schema.json; the spec schema is inferred from values.yaml '
                            '(krateo.io/values-schema: infer, rules 1): typed-open, with no authored constraints'}
COND_AUTHORED = {'type': 'ValuesSchemaAuthored', 'status': 'True', 'reason': 'Authored',
                 'message': 'the chart ships values.schema.json at its root'}
COND_FOLLOWER = {'type': 'ValuesSchemaAuthored', 'status': 'Unknown', 'reason': 'OwnedByAnotherDefinition',
                 'message': 'the CRD is generated by CompositionDefinition krateo-system/owner; see its ValuesSchemaAuthored condition'}

TITLE = 'This form is generated from the chart’s default values'
CREATE_BODY = ('The blueprint’s author didn’t describe its inputs, so each field is checked only against the type of its '
               'default. A value the chart can’t use fails when it deploys, not here.')
EDIT_BODY = 'Each change is checked only against the type of its default. A value the chart can’t use fails when it deploys.'
SIX = '6 fields accept any value: empty, lists, mixedKinds, nested.deep, nothing, ratio.'


def render(chart):
    with tempfile.TemporaryDirectory() as tmp:
        copy = os.path.join(tmp, 'chart')
        subprocess.run(['cp', '-r', chart, copy], check=True)
        meta = os.path.join(copy, 'Chart.yaml')
        with open(meta, encoding='utf-8') as fh:
            text = fh.read()
        for ph in ('CHART_VERSION', 'SOURCE_REF', 'APP_VERSION'):
            text = text.replace(ph, '0.0.0-test')
        with open(meta, 'w', encoding='utf-8') as fh:
            fh.write(text)
        out = subprocess.run(['helm', 'template', 't', copy], capture_output=True, text=True, check=True).stdout
    return {(d['kind'], d['metadata']['name']): d for d in yaml.safe_load_all(out) if isinstance(d, dict)}


def jq(prog, data):
    proc = subprocess.run([JQ, '-c', prog], input=json.dumps(data), capture_output=True, text=True, check=False)
    if proc.returncode != 0:
        raise AssertionError(proc.stderr.strip()[:400])
    return json.loads(proc.stdout)


def expr(doc, for_path):
    e = next(t['expression'] for t in doc['spec']['widgetDataTemplate'] if t['forPath'] == for_path).strip()
    assert e.startswith('${') and e.endswith('}'), e[:40]
    return e[2:-1]


def compdef(cond):
    conds = [{'type': 'Ready', 'status': 'True', 'reason': 'Available'}] + ([cond] if cond else [])
    return {'apiVersion': 'core.krateo.io/v1alpha1', 'kind': 'CompositionDefinition',
            'metadata': {'name': 'shop', 'namespace': 'krateo-system', 'creationTimestamp': '2026-11-22T10:00:00Z'},
            'spec': {'chart': {'repo': 'shop', 'version': '0.1.0'}},
            'status': {'apiVersion': 'composition.krateo.io/v0-1-0', 'kind': 'Shop', 'resource': 'shops', 'conditions': conds}}


def cm(raw):
    return None if raw is None else {'data': {'values.schema.json': raw}}


def formdef(prog, raw, cond):
    # The CRD too, as an admin reads it: without a ConfigMap the form falls back to it (and `notice` says so).
    crd = {'spec': {'versions': [{'name': 'v0-1-0', 'schema': {'openAPIV3Schema': {'properties': {'spec': {
        'type': 'object', 'properties': {'replicas': {'x-kubernetes-int-or-string': True}}}}}}}]}}
    data = {'name': 'shop', 'namespace': 'krateo-system', 'username': 'ada', 'compdef': compdef(cond),
            'jsonschema': cm(raw), 'crd': crd, 'namespaces': ['krateo-system']}
    return jq(prog, data)


def editdef(prog, raw):
    comp = {'apiVersion': 'composition.krateo.io/v0-1-0', 'kind': 'Shop',
            'metadata': {'name': 'web', 'namespace': 'demo'}, 'spec': {}}
    data = {'name': 'web', 'namespace': 'demo', 'found': [comp],
            'crds': [{'group': 'composition.krateo.io', 'kind': 'Shop', 'plural': 'shops', 'version': 'v0-1-0',
                      'cdNamespace': 'krateo-system'}],
            'jsonschema': cm(raw)}
    return jq(prog, data)


def detail(prog, raw, cond):
    data = {'name': 'shop', 'namespace': 'krateo-system', 'compdef': compdef(cond), 'jsonschema': cm(raw),
            'catalog': {'entries': {}}, 'comps': {'items': []}}
    return jq(prog, data)


def main():
    bp = render(BLUEPRINTS)
    cp = render(COMPOSITIONS)
    create_prog = bp[('RESTAction', 'blueprint-formdef')]['spec']['filter']
    create_notices = expr(bp[('Form', 'blueprint-create')], 'notices')
    edit_prog = cp[('RESTAction', 'composition-editdef')]['spec']['filter']
    edit_notices = expr(cp[('Form', 'composition-edit')], 'notices')
    detail_prog = bp[('RESTAction', 'blueprint-detail')]['spec']['filter']
    info_items = expr(bp[('Descriptions', 'descriptions-blueprint-detail-info')], 'items')
    bad = []

    def check(label, got, want):
        if got != want:
            bad.append(label)
            print(f'FAIL {label}:\n  got  {got!r}\n  want {want!r}')

    def create(raw, cond):
        return jq(create_notices, formdef(create_prog, raw, cond))

    def edit(raw):
        return jq(edit_notices, editdef(edit_prog, raw))

    def inputs_row(raw, cond):
        rows = jq(info_items, detail(detail_prog, raw, cond))
        return [r['value'] for r in rows if r['label'] == 'Inputs'], [r['label'] for r in rows]

    details = 'ValuesSchemaAuthored=False · InferredFromValues\n' + COND_INFERRED['message']
    check('create, inferred: the notice, its Details, no "accept any value"', create(CM_INFERRED, COND_INFERRED),
          [{'title': TITLE, 'description': [CREATE_BODY], 'details': details}])
    check('create, untyped: the fields a person sees, = core-provider\'s CRD-side list', create(CM_UNTYPED, COND_INFERRED),
          [{'title': TITLE, 'description': [CREATE_BODY, SIX], 'details': details}])
    check('create, untyped: NOT core-provider\'s report (it says lists[], the form says lists)',
          REPORT_UNTYPED != CRD_ANY_VALUE and ', '.join(CRD_ANY_VALUE) in SIX, True)
    check('create, authored: nothing', create(CM_AUTHORED, COND_AUTHORED), [])
    check('create, forged marker (stripped by core-provider): nothing', create(CM_FORGED, COND_AUTHORED), [])
    check('create, no ConfigMap: no notices (the CRD-fallback `notice` speaks)', create(None, COND_INFERRED), [])
    check('create, inferred but no condition (an older status): the notice, without Details', create(CM_UNTYPED, None),
          [{'title': TITLE, 'description': [CREATE_BODY, SIX]}])
    check('create, the CRD-fallback notice is unchanged', bool(formdef(create_prog, None, COND_INFERRED)['notice']), True)

    check('edit, untyped: the shorter notice, no Details', edit(CM_UNTYPED),
          [{'title': TITLE, 'description': [EDIT_BODY, SIX]}])
    check('edit, authored: nothing', edit(CM_AUTHORED), [])
    check('edit, no ConfigMap: nothing', edit(None), [])

    row, labels = inputs_row(CM_UNTYPED, COND_INFERRED)
    check('details, untyped: the Inputs line', row, ['Inferred from the chart’s default values · 6 fields accept any value'])
    check('details, the Inputs line follows the versions', labels[:4], ['Chart', 'Installed version', 'Latest version', 'Inputs'])
    check('details, inferred, typed: the line without a count', inputs_row(CM_INFERRED, COND_INFERRED)[0],
          ['Inferred from the chart’s default values'])
    check('details, authored: no Inputs row', inputs_row(CM_AUTHORED, COND_AUTHORED)[0], [])
    check('details, no ConfigMap: no Inputs row', inputs_row(None, COND_INFERRED)[0], [])
    check('details, follower: another blueprint defines it, no owner parsed from prose',
          inputs_row(None, COND_FOLLOWER)[0], ['Defined by another blueprint'])

    control = create_prog.replace('elif .type == "array" and ((.items == null) or (.items == {})) then $q',
                                  'elif false then $q', 1)
    if control == create_prog:
        bad.append('control')
        print('FAIL control: the items rule was not found in the shipped filter')
    else:
        got = jq(create_notices, formdef(control, CM_UNTYPED, COND_INFERRED))[0]['description'][1]
        if 'lists' in got or 'mixedKinds' in got:
            bad.append('control')
            print(f'FAIL control: without the items rule the list still names lists/mixedKinds: {got!r}')

    print(f'inferred inputs: create + edit + details over core-provider\'s sample, {len(bad)} failure(s)')
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
